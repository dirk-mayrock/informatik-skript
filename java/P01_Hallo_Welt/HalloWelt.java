/**
 * Praktikum 1 – Hallo Welt
 *
 * Das erste Java-Programm.
 * Ausgabe auf der Konsole mit System.out.println().
 *
 * Getränkeautomat – Schritt 1:
 * Wir geben eine Willkommensnachricht aus.
 */
public class HalloWelt {

    public static void main(String[] args) {

        // Einfache Ausgabe auf der Konsole
        System.out.println("Hallo, Welt!");

        // Mehrere Ausgaben hintereinander
        System.out.println("Ich lerne Java.");
        System.out.println("Das macht Spass!");

        // Eine leere Zeile ausgeben
        System.out.println();

        // --- Getränkeautomat Schritt 1 ---
        System.out.println("============================");
        System.out.println(" Willkommen beim");
        System.out.println(" Getraenkeautomaten!");
        System.out.println("============================");
        System.out.println("Wir haben leckere Getraenke.");
    }

}
